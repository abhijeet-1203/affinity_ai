#!/usr/bin/env python3
"""Assemble pod function bundles from the layered source.

The pod function sandbox gives each function exactly one `code.py`, with no
importable sibling modules. Rather than paste the engine into every handler (and
let the copies drift), the engine and the shared API layer are authored as real
modules and *inlined* at build time into each function that declares a marker:

    backend_src/handlers/<name>.py   -- header, models, handler, markers
    backend_src/common.py            -- session, auth, privacy, data access
    ml/affinity/*.py                 -- the compatibility engine

Run: python scripts/build_functions.py
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent

ENGINE_ORDER = [
    "text.py", "questionnaire.py", "weights.py", "similarity.py",
    "compatibility.py", "starters.py", "explain.py", "ranking.py", "evaluation.py",
]

GRANT_TABLES = [
    "aa_accounts", "aa_sessions", "aa_profiles", "aa_interests", "aa_profile_interests",
    "aa_questionnaire_responses", "aa_discovery_preferences", "aa_interactions", "aa_matches",
    "aa_saved_profiles", "aa_blocks", "aa_reports", "aa_feedback", "aa_recommendation_events",
    "aa_audit_logs", "aa_eval_runs",
]

DESCRIPTIONS = {
    "aa_auth": "AffinityAI accounts: register, sign in/out, session identity, password change and account deletion.",
    "aa_profile": "AffinityAI profile reads and edits, public profile card, interest catalogue and personalisation reset.",
    "aa_onboarding": "AffinityAI onboarding: profile, interests, questionnaire, discovery preferences, visibility and completion.",
    "aa_discovery": "AffinityAI matching: eligibility, compatibility scoring, explainable recommendations, feedback and conversation starters.",
    "aa_interactions": "AffinityAI interactions: like, pass, save, block, report, withdraw and per-member collections.",
    "aa_matches": "AffinityAI mutual matches: list, detail and withdraw. Matches require reciprocal interest.",
    "aa_insights": "AffinityAI personal analytics computed only from the caller's own persisted activity.",
    "aa_seed": "AffinityAI demo seeder: deterministic, clearly labelled fictional members.",
    "aa_eval": "AffinityAI evaluation: runs the engine over the synthetic labelled set and stores measured metrics.",
}


def strip_local_imports(source, package):
    kept = []
    for line in source.splitlines():
        if re.match(r"^\s*from \." + package if package else r"^\s*from \.", line):
            continue
        if line.startswith("from affinity"):
            continue
        if line.startswith("import affinity"):
            continue
        if line.startswith("from ."):
            continue
        kept.append(line)
    return "\n".join(kept).strip("\n")


def common_block():
    source = (ROOT / "backend_src" / "common.py").read_text()
    return source.strip("\n")


def engine_block():
    parts = ["# --- inlined: ml/affinity/*.py (generated by scripts/build_functions.py) ---"]
    for name in ENGINE_ORDER:
        source = strip_local_imports((ROOT / "ml" / "affinity" / name).read_text(), "")
        parts.append(f"\n# ---- ml/affinity/{name} ----\n{source}")
    return "\n".join(parts)


def build():
    handlers_dir = ROOT / "backend_src" / "handlers"
    out_root = ROOT / "pod" / "functions"
    out_root.mkdir(parents=True, exist_ok=True)
    common = common_block()
    engine = engine_block()
    built = []
    for handler_path in sorted(handlers_dir.glob("*.py")):
        name = handler_path.stem
        source = handler_path.read_text()
        if "# @@INLINE:common@@" in source:
            source = source.replace("# @@INLINE:common@@", common)
        if "# @@INLINE:engine@@" in source:
            source = source.replace("# @@INLINE:engine@@", engine)
        else:
            source = source.replace("# @@INLINE:engine@@", "")
        target = out_root / name
        target.mkdir(parents=True, exist_ok=True)
        (target / "code.py").write_text(source)
        manifest = {
            "name": name,
            "description": DESCRIPTIONS.get(name, f"AffinityAI function {name}."),
            "type": "API",
            "visibility": "POD",
            "code": {"$file": "code.py"},
            "permissions": {"grants": [
                {"resource_type": "datastore_table", "resource_name": table,
                 "permission_ids": ["datastore.table.read", "datastore.record.read",
                                    "datastore.record.write"]}
                for table in GRANT_TABLES
            ]},
        }
        (target / f"{name}.json").write_text(json.dumps(manifest, indent=2) + "\n")
        built.append(f"{name}: {len(source.splitlines())} lines")
    print("\n".join(built))
    print(f"\n{len(built)} functions built into {out_root}")


if __name__ == "__main__":
    build()
